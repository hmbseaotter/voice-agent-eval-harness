"""Generate `corpus/findings.yaml` from the drafts and the adjudication ledger.

    uv run python tools/make_gold_set.py
    uv run python tools/make_gold_set.py --check

WHY THIS IS GENERATED RATHER THAN WRITTEN
-----------------------------------------
D36 kept the gold set from existing until a human had made it, because a file at
the gold set's path in the gold set's schema *is* the gold set to every tool
downstream. That is now satisfied: every candidate carries a ruling in
`corpus/findings.adjudication.yaml`, and this tool projects the two files into
one.

Generating rather than hand-assembling buys the property the absence was
protecting. The gold set is reproducible from its inputs, so a later correction
to a ruling cannot drift from the artifact built out of it -- which is the
failure this project has caught in itself repeatedly, most recently in three
findings carrying figures from a superseded header that no check read.

WHAT WINS WHERE
---------------
`owner`, `detectable_by` and `tier` come from the **ledger**. The drafts state
what a model proposed; the ledger states what a human ruled, and D10 makes the
ruling the ground truth. Two rows differ today and both are deliberate: F-05's
tier and F-10's `detectable_by`.

`observation`, `evidence` and `consequence` come from the ledger **where it
carries them**, and from the drafts otherwise. A row marked `accept-with-edits`
whose ledger entry has no replacement text was corrected mechanically rather
than rewritten by judgment -- a stale timestamp, a citation that moved when a
transcript gained events -- and a corrected draft belongs in the drafts file.

`verdict` and `note` are the ledger's own and are projected out: the gold set
carries the eight keys `harness.core.findings` requires and nothing else, since
that loader tolerates no unknown key.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any, Final

import yaml

REPO_ROOT: Final[Path] = Path(__file__).resolve().parents[1]
CANDIDATES: Final[Path] = REPO_ROOT / "corpus" / "findings.candidates.yaml"
LEDGER: Final[Path] = REPO_ROOT / "corpus" / "findings.adjudication.yaml"
OUT: Final[Path] = REPO_ROOT / "corpus" / "findings.yaml"

#: The order `harness.core.findings.REQUIRED_KEYS` declares. Not re-typed as a
#: literal set -- the import is the point, so adding a key there fails here.
sys.path.insert(0, str(REPO_ROOT / "src"))
from harness.core.findings import REQUIRED_KEYS  # noqa: E402

VERDICTS: Final[frozenset[str]] = frozenset({"accept", "accept-with-edits", "reject"})
RULED: Final[tuple[str, ...]] = ("owner", "detectable_by", "tier")
TEXT: Final[tuple[str, ...]] = ("observation", "evidence", "consequence")

HEADER: Final[str] = """\
# The gold set. Generated by `tools/make_gold_set.py` from:
#
#   corpus/findings.candidates.yaml   the model's drafts
#   corpus/findings.adjudication.yaml the human's rulings
#
# Do not edit this file. Edit the ledger and regenerate, or the two drift and
# the drift is invisible -- which is the failure the generation exists to
# prevent. `--check` fails if this file and its inputs disagree.
#
# WHAT THIS FILE IS FOR. The judge is validated by agreement with these rows,
# so if they were model-generated that agreement would measure a model against
# itself and the project's headline claim would be empty (D10). The rows,
# `owner`, `detectable_by` and `tier` are a human's judgment; the reasoning
# behind each one is in the ledger, one entry per id.
#
# `owner` and `call_ref` are harness-side and are not read by the severity
# tool, which uses the other six (D54).
"""


def _block(text: str, indent: str) -> str:
    """A YAML literal scalar, for text whose line breaks are part of the content.

    D22 chose YAML over a Markdown table because evidence may hold verbatim
    multi-line quotes and a table cell cannot carry a newline. No row in the
    corpus is known to need one -- an independent sweep found none across every row
    then present, and rows added since have not been re-checked --
    and the folding path would have flattened one silently if a row ever did,
    turning the format's whole justification into something only a fixture
    exercised. Emitting a literal scalar makes the affordance real rather than
    asserted, and the round-trip is tested.
    """
    return "\n".join(indent + line if line.strip() else "" for line in str(text).split("\n"))


def _fold(text: str, indent: str) -> str:
    """A YAML folded scalar, wrapped the way the candidates file wraps."""
    words, lines, cur = str(text).split(), [], ""
    for word in words:
        if cur and len(indent) + len(cur) + 1 + len(word) > 78:
            lines.append(indent + cur)
            cur = word
        else:
            cur = f"{cur} {word}" if cur else word
    if cur:
        lines.append(indent + cur)
    return "\n".join(lines)


def _marker(text: object) -> str:
    """`|-` where line breaks are content, `>-` where they are only wrapping."""
    return "|-" if "\n" in str(text) else ">-"


def _scalar(text: object, indent: str) -> str:
    return _block(str(text), indent) if "\n" in str(text) else _fold(str(text), indent)


def _render(entry: dict[str, Any]) -> str:
    out = [
        f"  - id: {entry['id']}",
        f"    call_ref: {entry['call_ref']}",
        f"    owner: {entry['owner']}",
    ]
    out.append("    observation: " + _marker(entry["observation"]))
    out.append(_scalar(entry["observation"], "      "))
    out.append("    evidence:")
    for fragment in entry["evidence"]:
        out.append("      - " + _marker(fragment))
        out.append(_scalar(fragment, "        "))
    out.append("    consequence: " + _marker(entry["consequence"]))
    out.append(_scalar(entry["consequence"], "      "))
    out.append(f"    detectable_by: {entry['detectable_by']}")
    out.append(f"    tier: {entry['tier']}")
    return "\n".join(out)


def build() -> str:
    drafts = {
        r["id"]: r for r in yaml.safe_load(CANDIDATES.read_text(encoding="utf-8"))["findings"]
    }
    rulings = {
        x["id"]: x for x in yaml.safe_load(LEDGER.read_text(encoding="utf-8"))["adjudications"]
    }

    unruled = sorted(set(drafts) - set(rulings), key=lambda s: int(s[2:]))
    if unruled:
        raise SystemExit(
            "the gold set cannot be generated: no ruling for "
            + ", ".join(unruled)
            + "\nD36 makes that deliberate -- adjudicate first."
        )
    orphaned = sorted(set(rulings) - set(drafts), key=lambda s: int(s[2:]))
    if orphaned:
        raise SystemExit(f"the ledger rules on findings that do not exist: {orphaned}")

    rows: list[dict[str, Any]] = []
    for fid in sorted(drafts, key=lambda s: int(s[2:])):
        ruling = rulings[fid]
        verdict = ruling["verdict"]
        # Without this, `rejcet` is not a rejection -- it is an acceptance, and
        # the row publishes silently. Every other string was treated as assent.
        if verdict not in VERDICTS:
            raise SystemExit(f"{fid}: verdict {verdict!r} is not one of {sorted(VERDICTS)}")
        if verdict == "accept" and any(key in ruling for key in TEXT):
            raise SystemExit(
                f"{fid}: verdict is `accept` yet the ledger carries replacement text. "
                "Use `accept-with-edits`, or drop the text."
            )
        if verdict == "reject":
            continue
        row = {"id": fid, "call_ref": drafts[fid]["call_ref"]}
        row |= {key: ruling[key] for key in RULED}
        row |= {key: ruling.get(key, drafts[fid][key]) for key in TEXT}
        missing = [k for k in REQUIRED_KEYS if k not in row]
        if missing:
            raise SystemExit(f"{fid}: missing {missing} after projection")
        rows.append(row)

    body = "\n\n".join(_render(row) for row in rows)
    return f"{HEADER}\nfindings:\n{body}\n"


def main(*, check: bool = False) -> int:
    rendered = build()
    where = OUT.relative_to(REPO_ROOT).as_posix()
    if check:
        if not OUT.is_file():
            print(f"{where} has not been generated", file=sys.stderr)
            return 1
        if OUT.read_text(encoding="utf-8") != rendered:
            print(f"{where} disagrees with its inputs; regenerate it", file=sys.stderr)
            return 1
        print(f"{where} agrees with the drafts and the ledger")
        return 0
    with OUT.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(rendered)
    count = rendered.count("\n  - id: ")
    print(f"wrote {where} — {count} findings, generated from the drafts and the ledger")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate the gold set.")
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if the gold set disagrees with its inputs"
    )
    raise SystemExit(main(check=parser.parse_args().check))
